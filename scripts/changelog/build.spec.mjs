const facility = { afterEach, beforeEach, describe, it };

const LEGEND = `Legends:

- 💥 are breaking changes
- 👷🏻 are development environment changes`;

async function createFragmentDirectory(files) {
  const directoryPath = join(await mkdtemp(join(tmpdir(), 'changelog-build-')), '.changelog');

  await mkdir(directoryPath);

  for (const [filename, content] of Object.entries(files)) {
    await writeFile(join(directoryPath, filename), content);
  }

  return directoryPath;
}

function removeFragmentDirectory(directoryPath) {
  return rm(join(directoryPath, '..'), { force: true, recursive: true });
}

