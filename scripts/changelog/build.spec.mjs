scenario(
  'ordering entries',
  bdd => {
    const ADDED_TIMES = Object.freeze({
      '5889-relative-video-url.md': 100,
      '5903-single-media.md': 200,
      '5905-positive-button.md': 200, // Same commit as #5903
      '5920-hour-cycle.md': undefined, // Not committed yet
      '5926-carousel-scroll.md': undefined // Not committed yet
    });

    bdd
      .given(
        'fragments added at different times',
        () =>
          createFragmentDirectory(
            Object.fromEntries(
              Object.keys(ADDED_TIMES).map(filename => [filename, `### Fixed\n\n- Fixed in ${filename}\n`])
            )
          ),
        removeFragmentDirectory
      )
      .when('read', directoryPath =>
        readFragments(directoryPath, { getAddedTime: path => ADDED_TIMES[basename(path)] })
      )
      .then('should be ordered by time added, then uncommitted ones, then by pull request number', (_, fragments) =>
        expect(fragments.map(({ prNumber }) => prNumber)).toEqual([5889, 5903, 5905, 5920, 5926])
      );
  },
  facility
);

scenario(
  'getting the time a fragment was added with Git',
  bdd => {
    const git = (cwd, args, date) =>
      execFileSync('git', ['-c', 'user.email=test@example.com', '-c', 'user.name=Test', ...args], {
        cwd,
        env: { ...process.env, GIT_AUTHOR_DATE: date, GIT_COMMITTER_DATE: date }
      });

    bdd
      .given(
        'a Git repository with fragments committed on different days',
        async () => {
          const directoryPath = await createFragmentDirectory({});
          const repositoryPath = join(directoryPath, '..');

          git(repositoryPath, ['init', '--quiet']);

          await writeFile(join(directoryPath, '5926-carousel-scroll.md'), '### Fixed\n\n- Fixed 5926\n');
          git(repositoryPath, ['add', '.']);
          git(repositoryPath, ['commit', '--quiet', '-m', '#5926'], '2026-10-19T00:00:00Z');

          await writeFile(join(directoryPath, '5920-hour-cycle.md'), '### Fixed\n\n- Fixed 5920\n');
          git(repositoryPath, ['add', '.']);
          git(repositoryPath, ['commit', '--quiet', '-m', '#5920'], '2026-10-20T00:00:00Z');

          // Edited later, still counts as added on 2026-10-19.
          await writeFile(join(directoryPath, '5926-carousel-scroll.md'), '### Fixed\n\n- Fixed 5926, edited\n');
          git(repositoryPath, ['commit', '--all', '--quiet', '-m', 'Edit #5926'], '2026-10-21T00:00:00Z');

          await writeFile(join(directoryPath, '5900-not-committed.md'), '### Fixed\n\n- Fixed 5900\n');

          return directoryPath;
        },
        removeFragmentDirectory
      )
      .when('read', directoryPath => readFragments(directoryPath))
      .then('should get the commit time', directoryPath => {
        expect(getGitAddedTime(join(directoryPath, '5926-carousel-scroll.md'))).toBe(Date.UTC(2026, 9, 19) / 1000);
        expect(getGitAddedTime(join(directoryPath, '5920-hour-cycle.md'))).toBe(Date.UTC(2026, 9, 20) / 1000);
      })
      .and('should be undefined for uncommitted files', directoryPath =>
        expect(getGitAddedTime(join(directoryPath, '5900-not-committed.md'))).toBeUndefined()
      )
      .and('should order by the time added, not by pull request number or edit time', (_, fragments) =>
        expect(fragments.map(({ prNumber }) => prNumber)).toEqual([5926, 5920, 5900])
      );
  },
  facility
);

scenario(
  'reading invalid fragments',
  bdd => {
    const read = async files => {
      const directoryPath = await createFragmentDirectory(files);

      try {
        return await readFragments(directoryPath, { getAddedTime: () => undefined });
      } catch (error) {
        return error;
      } finally {
        await removeFragmentDirectory(directoryPath);
      }
    };

    bdd
      .given('a section not used in CHANGELOG.md', () => ({ '1-a.md': '### Deprecated\n\n- Deprecated something\n' }))
      .when('read', read)
      .then('should fail', (_, error) =>
        expect(error).toHaveProperty(
          'message',
          '1-a.md:1: unknown section "Deprecated", use one of: Added, Changed, Removed, Fixed'
        )
      );

    bdd
      .given('a section twice', () => ({ '1-a.md': '### Fixed\n\n- Fixed a\n\n### Fixed\n\n- Fixed b\n' }))
      .when('read', read)
      .then('should fail', (_, error) =>
        expect(error).toHaveProperty('message', '1-a.md:5: section "Fixed" appears more than once')
      );

    bdd
      .given('an entry without section', () => ({ '1-a.md': '- Fixed a\n' }))
      .when('read', read)
      .then('should fail', (_, error) =>
        expect(error).toHaveProperty('message', '1-a.md:1: entry must be under a "### <section>" heading')
      );

    bdd
      .given('a paragraph', () => ({ '1-a.md': '### Fixed\n\nFixed a\n' }))
      .when('read', read)
      .then('should fail', (_, error) =>
        expect(error).toHaveProperty(
          'message',
          '1-a.md:3: expected "### <section>", "- <entry>", or an indented line, got "Fixed a"'
        )
      );

    bdd
      .given('a nested line indented by 2 spaces', () => ({ '1-a.md': '### Fixed\n\n- Fixed a\n  - b\n' }))
      .when('read', read)
      .then('should fail', (_, error) =>
        expect(error).toHaveProperty('message', '1-a.md:4: indent nested lines by 3 spaces per level, without tabs')
      );

    bdd
      .given('a nested line indented by a tab', () => ({ '1-a.md': '### Fixed\n\n- Fixed a\n\t- b\n' }))
      .when('read', read)
      .then('should fail', (_, error) =>
        expect(error).toHaveProperty('message', '1-a.md:4: indent nested lines by 3 spaces per level, without tabs')
      );

    bdd
      .given('an empty section', () => ({ '1-a.md': '### Fixed\n' }))
      .when('read', read)
      .then('should fail', (_, error) =>
        expect(error).toHaveProperty('message', '1-a.md: section "Fixed" has no entries')
      );

    bdd
      .given('an empty file', () => ({ '1-a.md': '' }))
      .when('read', read)
      .then('should fail', (_, error) => expect(error).toHaveProperty('message', '1-a.md: fragment has no entries'));

    bdd
      .given('a file without pull request number', () => ({ 'fix-something.md': '### Fixed\n\n- Fixed a\n' }))
      .when('read', read)
      .then('should fail', (_, error) =>
        expect(error).toHaveProperty(
          'message',
          '.changelog/fix-something.md: fragment filename must be "<PR#>-<slug>.md"'
        )
      );
  },
  facility
);

scenario(
  'previewing the entries of a pull request',
  bdd => {
    const fragments = Object.freeze([
      Object.freeze({
        filename: '5920-hour-cycle.md',
        prNumber: 5920,
        sections: Object.freeze({ Fixed: Object.freeze(['- Fixed timestamps']) })
      }),
      Object.freeze({
        filename: '5926-carousel-scroll.md',
        prNumber: 5926,
        sections: Object.freeze({ Fixed: Object.freeze(['- Fixed carousel']) })
      })
    ]);

    bdd
      .given('a pull request with a fragment', () => ({ optional: false, prNumber: 5920 }))
      .when('previewed', init => renderPreview(fragments, init))
      .then('should show only its entries', (_, preview) =>
        expect(preview).toBe(
          '## Changelog\n\nFrom `.changelog/5920-hour-cycle.md`, published to [`UNRELEASED.md`](https://github.com/microsoft/BotFramework-WebChat/blob/changelog-unreleased/UNRELEASED.md) when merged:\n\n### Fixed\n\n- Fixed timestamps\n'
        )
      );

    bdd
      .given('a pull request without fragment', () => ({ optional: false, prNumber: 5930 }))
      .when('previewed', init => () => renderPreview(fragments, init))
      .then('should fail', (_, preview) => expect(preview).toThrow('Missing .changelog/5930-<slug>.md'));

    bdd
      .given('a pull request labeled "no-changelog" without fragment', () => ({ optional: true, prNumber: 5930 }))
      .when('previewed', init => renderPreview(fragments, init))
      .then('should say there are no entries', (_, preview) =>
        expect(preview).toBe('## Changelog\n\nNo entries, labeled `no-changelog`.\n')
      );

    bdd
      .given('a pull request with two fragments', () => ({ optional: false, prNumber: 5920 }))
      .when(
        'previewed',
        init => () => renderPreview([...fragments, { ...fragments[0], filename: '5920-another.md' }], init)
      )
      .then('should fail', (_, preview) =>
        expect(preview).toThrow(
          'Found 2 fragments for #5920 (5920-hour-cycle.md, 5920-another.md), use one file per pull request'
        )
      );
  },
  facility
);

