scenario(
  'checking the "[Unreleased]" section of CHANGELOG.md',
  bdd => {
    const changelog = body => `# Changelog\n\n${LEGEND}\n\n## [Unreleased]\n\n${body}\n\n## [4.19.2] - 2026-10-08\n`;

    bdd
      .given('only the link to UNRELEASED.md', () => changelog(UNRELEASED_NOTE))
      .when('checked', markdown => () => validateUnreleasedSection(markdown))
      .then('should pass', (_, check) => expect(check).not.toThrow());

    bdd
      .given('an entry added by a pull request', () =>
        changelog(
          `${UNRELEASED_NOTE}\n\n### Fixed\n\n- Fixed a, in PR [#5930](https://github.com/microsoft/BotFramework-WebChat/pull/5930), by [@OEvgeny](https://github.com/OEvgeny)`
        )
      )
      .when('checked', markdown => () => validateUnreleasedSection(markdown))
      .then('should fail and ask for a fragment', (_, check) =>
        expect(check).toThrow(
          'CHANGELOG.md: the "[Unreleased]" section was edited, add a .changelog/<PR#>-<slug>.md fragment instead'
        )
      );

    bdd
      .given('the link removed', () => changelog(''))
      .when('checked', markdown => () => validateUnreleasedSection(markdown))
      .then('should fail', (_, check) => expect(check).toThrow('the "[Unreleased]" section was edited'));
  },
  facility
);
